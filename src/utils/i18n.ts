export type TranslationKey = keyof typeof translations.en;

export const useTranslation = (lang: Language = 'en') => {
  const currentLang: Language = lang === 'ta' ? 'ta' : 'en';
  
  const t = (key: TranslationKey): string => {
    const dict = translations[currentLang] as Record<string, string>;
    return dict[key] || translations.en[key] || key;
  };

  const getCategoryName = (categoryId: string, defaultName: string): string => {
    if (CATEGORY_TRANSLATIONS[categoryId]) {
      return CATEGORY_TRANSLATIONS[categoryId][currentLang] || defaultName;
    }
    return defaultName;
  };

  const getPaymentModeLabel = (modeId: string, defaultLabel: string): string => {
    if (PAYMENT_MODE_TRANSLATIONS[modeId]) {
      return PAYMENT_MODE_TRANSLATIONS[modeId][currentLang] || defaultLabel;
    }
    return defaultLabel;
  };

  return { t, getCategoryName, getPaymentModeLabel, currentLang };
};
